import fs from 'node:fs';
import net from 'node:net';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';

const output = path.resolve(process.argv[2] || '../evidence/phase1a-sse-slow-reader.json');
const port = 38100 + Math.floor(Math.random() * 200);
const origin = `http://127.0.0.1:${port}`;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'cockpit-sse-pressure-'));
const child = spawn(process.execPath, ['server.js'], { cwd: path.resolve(import.meta.dirname, '..'), env: { ...process.env, HOST: '127.0.0.1', PORT: String(port), COCKPIT_DATA_DIR: dir, COCKPIT_DISABLE_ACQUISITION: '1', COCKPIT_TEST_SSE_PAYLOAD_BYTES: String(128 * 1024), COCKPIT_TEST_SSE_REPEATS: '64' }, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
let stdout = '';
child.stdout.on('data', d => { stdout += d; });
await new Promise((resolve, reject) => { const t = setTimeout(() => reject(Error('startup timeout')), 5000); child.stdout.on('data', () => { if (stdout.includes('listening')) { clearTimeout(t); resolve(); } }); child.once('error', reject); });
const token = fs.readFileSync(path.join(dir, 'auth', 'bootstrap.token'), 'utf8');
const enroll = await fetch(origin + '/api/enroll', { method: 'POST', headers: { origin, 'content-type': 'application/json' }, body: JSON.stringify({ token, password: 'long-test-password' }) });
const cookie = enroll.headers.get('set-cookie').split(';')[0];
const socket = net.connect({ host: '127.0.0.1', port });
socket.pause();
await new Promise(resolve => socket.once('connect', resolve));
socket.write(`GET /api/stream HTTP/1.1\r\nHost: 127.0.0.1:${port}\r\nCookie: ${cookie}\r\nConnection: keep-alive\r\n\r\n`);
await new Promise(resolve => setTimeout(resolve, 100));
await fetch(origin + '/healthz?pressure=1');
await new Promise(resolve => setTimeout(resolve, 1000));
let observedClose = false;
socket.once('close', () => { observedClose = true; });
socket.once('end', () => { observedClose = true; });
socket.resume();
await new Promise(resolve => setTimeout(resolve, 2000));
const disconnected = observedClose || socket.destroyed || socket.readableEnded || socket.closed;
socket.destroy(); child.kill('SIGTERM'); await new Promise(resolve => child.once('exit', resolve)); fs.rmSync(dir, { recursive: true, force: true });
const report = { status: disconnected ? 'PASS' : 'UNVERIFIED', transportLevel: true, payloadBytes: 128 * 1024 * 64, expected: 'server disconnects slow reader above 256KiB writable buffer', observedDisconnected: disconnected, note: disconnected ? 'TCP client was closed after pressure broadcast' : 'Loopback TCP buffering did not expose server writableLength above the threshold; predicate evidence remains separate' };
fs.mkdirSync(path.dirname(output), { recursive: true }); fs.writeFileSync(output, JSON.stringify(report, null, 2) + '\n'); console.log(JSON.stringify(report));
